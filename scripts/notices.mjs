// Write THIRD_PARTY_NOTICES.txt next to the built bundle: the license of every production
// package in package-lock.json (design doc 12 §8). Runs as the last step of `npm run build`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { appDir } from "./app-dir.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const out = join(appDir(), "THIRD_PARTY_NOTICES.txt");
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));

const entries = Object.entries(lock.packages)
  .filter(([path, meta]) => path.startsWith("node_modules/") && !meta.dev && !meta.optional)
  .map(([path, meta]) => ({ path, name: path.replace(/^.*node_modules\//, ""), version: meta.version, license: meta.license }))
  .sort((a, b) => a.name.localeCompare(b.name));

const sections = entries.map(({ path, name, version, license }) => {
  const dir = join(root, path);
  const file = existsSync(dir) ? readdirSync(dir).find((f) => /^licen[cs]e(\.|$)/i.test(f)) : undefined;
  const text = file ? readFileSync(join(dir, file), "utf8").trim() : `License: ${license ?? "see package"}`;
  return `${name} ${version} (${license ?? "unknown"})\n${"-".repeat(72)}\n${text}\n`;
});

writeFileSync(
  out,
  "Third-party software bundled in the brain-wiki visualizer (src/brainwiki/viz/app).\n" +
    "Generated by brain-wiki-viz scripts/notices.mjs; do not edit.\n\n" +
    sections.join("\n"),
);
console.log(`notices: ${entries.length} packages -> ${out}`);
